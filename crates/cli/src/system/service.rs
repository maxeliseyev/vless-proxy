//! `vproxy service install|uninstall|status|logs`: run vproxy in the
//! background as a launchd (macOS) or systemd (Linux) service, so it keeps
//! working after the terminal is closed and starts at boot. `--tun` installs a
//! system daemon (root); without it a per-user agent/unit for the local proxy.

use anyhow::{bail, Context, Result};
use std::path::{Path, PathBuf};
use std::process::Command;

/// The real user's home even under `sudo` (so a service installed with sudo
/// still lands in the user's `~`, not root's).
pub fn real_home() -> Option<PathBuf> {
    if let Some(user) = std::env::var_os("SUDO_USER") {
        let user = user.to_string_lossy();
        if user != "root" {
            let candidate = if cfg!(target_os = "macos") {
                PathBuf::from("/Users").join(&*user)
            } else {
                PathBuf::from("/home").join(&*user)
            };
            if candidate.is_dir() {
                return Some(candidate);
            }
        }
    }
    std::env::var_os("HOME").map(PathBuf::from)
}

/// What the installed service should run.
pub struct ServicePlan {
    pub tun: bool,
    /// `vproxy` binary, absolute.
    pub binary: PathBuf,
    /// Arguments after the binary: config source, port, flags.
    pub args: Vec<String>,
}

pub struct Paths {
    pub unit: PathBuf,
    pub log: PathBuf,
    pub label: String,
}

fn is_root() -> bool {
    // SAFETY: getuid has no preconditions.
    unsafe { libc::getuid() == 0 }
}

fn home() -> Result<PathBuf> {
    real_home().context("HOME is not set")
}

/// Where the unit file and log live for this mode.
pub fn paths(tun: bool) -> Result<Paths> {
    let label = if tun {
        "com.vproxy.tun"
    } else {
        "com.vproxy.local"
    }
    .to_string();
    Ok(if cfg!(target_os = "macos") {
        if tun {
            Paths {
                unit: PathBuf::from("/Library/LaunchDaemons").join(format!("{label}.plist")),
                log: PathBuf::from("/var/log/vproxy.log"),
                label,
            }
        } else {
            let h = home()?;
            Paths {
                unit: h
                    .join("Library/LaunchAgents")
                    .join(format!("{label}.plist")),
                log: h.join("Library/Logs/vproxy.log"),
                label,
            }
        }
    } else if tun {
        Paths {
            unit: PathBuf::from("/etc/systemd/system/vproxy.service"),
            log: PathBuf::from("journalctl -u vproxy"),
            label: "vproxy".to_string(),
        }
    } else {
        Paths {
            unit: home()?.join(".config/systemd/user/vproxy.service"),
            log: PathBuf::from("journalctl --user -u vproxy"),
            label: "vproxy".to_string(),
        }
    })
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// launchd property list for the plan.
pub fn render_plist(plan: &ServicePlan, p: &Paths) -> String {
    let mut args = vec![plan.binary.display().to_string()];
    args.extend(plan.args.iter().cloned());
    let items: String = args
        .iter()
        .map(|a| format!("    <string>{}</string>\n", xml_escape(a)))
        .collect();
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- generated by `vproxy service install`; remove with `vproxy service uninstall` -->
<plist version="1.0">
<dict>
  <key>Label</key><string>{label}</string>
  <key>ProgramArguments</key>
  <array>
{items}  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>{log}</string>
  <key>StandardErrorPath</key><string>{log}</string>
</dict>
</plist>
"#,
        label = p.label,
        log = xml_escape(&p.log.display().to_string()),
    )
}

fn shell_quote(s: &str) -> String {
    if s.bytes()
        .all(|b| b.is_ascii_alphanumeric() || b"-_./:=@+,".contains(&b))
    {
        s.to_string()
    } else {
        // systemd expands `%` specifiers and `$` variables inside quotes too.
        format!(
            "\"{}\"",
            s.replace('\\', "\\\\")
                .replace('"', "\\\"")
                .replace('%', "%%")
                .replace('$', "$$")
        )
    }
}

/// systemd unit for the plan.
pub fn render_unit(plan: &ServicePlan) -> String {
    let mut exec = vec![shell_quote(&plan.binary.display().to_string())];
    exec.extend(plan.args.iter().map(|a| shell_quote(a)));
    let privileges = if plan.tun {
        "User=root\nAmbientCapabilities=CAP_NET_ADMIN CAP_NET_BIND_SERVICE\n"
    } else {
        ""
    };
    format!(
        "# generated by `vproxy service install`; remove with `vproxy service uninstall`
[Unit]
Description=vproxy VLESS client{tun}
After=network-online.target
Wants=network-online.target

[Service]
ExecStart={exec}
Restart=on-failure
RestartSec=3
{privileges}LimitNOFILE=65536

[Install]
WantedBy={target}
",
        tun = if plan.tun { " (TUN)" } else { "" },
        exec = exec.join(" "),
        target = if plan.tun {
            "multi-user.target"
        } else {
            "default.target"
        },
    )
}

fn run(cmd: &str, args: &[&str]) -> Result<std::process::Output> {
    Command::new(cmd)
        .args(args)
        .output()
        .with_context(|| format!("cannot run {cmd}"))
}

fn run_ok(cmd: &str, args: &[&str]) -> Result<()> {
    let out = run(cmd, args)?;
    if !out.status.success() {
        bail!(
            "{cmd} {} failed: {}{}",
            args.join(" "),
            String::from_utf8_lossy(&out.stdout).trim(),
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(())
}

fn require_privileges(tun: bool) -> Result<()> {
    if tun && !is_root() {
        bail!("installing the system-wide (TUN) service needs root: sudo vproxy service ...");
    }
    Ok(())
}

fn uid() -> u32 {
    // SAFETY: getuid has no preconditions.
    unsafe { libc::getuid() }
}

fn launchd_domain(tun: bool) -> String {
    if tun {
        "system".to_string()
    } else {
        format!("gui/{}", uid())
    }
}

/// Write the unit and start it (replacing an existing one).
pub fn install(plan: &ServicePlan) -> Result<Paths> {
    require_privileges(plan.tun)?;
    let p = paths(plan.tun)?;
    let _ = stop_quiet(plan.tun, &p);
    if let Some(dir) = p.unit.parent() {
        std::fs::create_dir_all(dir).with_context(|| format!("cannot create {}", dir.display()))?;
    }
    if cfg!(target_os = "macos") {
        std::fs::write(&p.unit, render_plist(plan, &p))
            .with_context(|| format!("cannot write {}", p.unit.display()))?;
        if let Some(dir) = p.log.parent() {
            let _ = std::fs::create_dir_all(dir);
        }
        run_ok(
            "launchctl",
            &[
                "bootstrap",
                &launchd_domain(plan.tun),
                &p.unit.display().to_string(),
            ],
        )?;
    } else {
        std::fs::write(&p.unit, render_unit(plan))
            .with_context(|| format!("cannot write {}", p.unit.display()))?;
        let user = if plan.tun { vec![] } else { vec!["--user"] };
        let mut a = user.clone();
        a.push("daemon-reload");
        run_ok("systemctl", &a)?;
        let mut a = user;
        a.extend(["enable", "--now", "vproxy"]);
        run_ok("systemctl", &a)?;
    }
    Ok(p)
}

fn stop_quiet(tun: bool, p: &Paths) -> Result<()> {
    if cfg!(target_os = "macos") {
        let target = format!("{}/{}", launchd_domain(tun), p.label);
        let _ = run("launchctl", &["bootout", &target]);
    } else {
        let user = if tun { vec![] } else { vec!["--user"] };
        let mut a = user;
        a.extend(["disable", "--now", "vproxy"]);
        let _ = run("systemctl", &a);
    }
    Ok(())
}

/// Stop the service and remove its unit file.
pub fn uninstall(tun: bool) -> Result<Paths> {
    require_privileges(tun)?;
    let p = paths(tun)?;
    stop_quiet(tun, &p)?;
    if p.unit.exists() {
        std::fs::remove_file(&p.unit)
            .with_context(|| format!("cannot remove {}", p.unit.display()))?;
    }
    if !cfg!(target_os = "macos") {
        let user = if tun { vec![] } else { vec!["--user"] };
        let mut a = user;
        a.push("daemon-reload");
        let _ = run("systemctl", &a);
    }
    Ok(p)
}

/// Human-readable status text.
pub fn status(tun: bool) -> Result<String> {
    let p = paths(tun)?;
    let mut text = format!(
        "unit: {}{}\n",
        p.unit.display(),
        if p.unit.exists() {
            ""
        } else {
            " (not installed)"
        }
    );
    let out = if cfg!(target_os = "macos") {
        let target = format!("{}/{}", launchd_domain(tun), p.label);
        run("launchctl", &["print", &target])?
    } else {
        let user = if tun { vec![] } else { vec!["--user"] };
        let mut a = user;
        a.extend(["status", "vproxy", "--no-pager"]);
        run("systemctl", &a)?
    };
    if out.status.success() {
        let s = String::from_utf8_lossy(&out.stdout);
        if cfg!(target_os = "macos") {
            for line in s.lines() {
                let l = line.trim();
                if l.starts_with("state =") || l.starts_with("pid =") || l.starts_with("last exit")
                {
                    text.push_str(l);
                    text.push('\n');
                }
            }
        } else {
            text.push_str(&s);
        }
    } else {
        text.push_str("not running\n");
    }
    text.push_str(&format!("logs: {}\n", p.log.display()));
    Ok(text)
}

/// Follow the logs (blocks).
pub fn logs(tun: bool) -> Result<()> {
    let p = paths(tun)?;
    let status = if cfg!(target_os = "macos") {
        Command::new("tail").arg("-f").arg(&p.log).status()?
    } else {
        let mut c = Command::new("journalctl");
        if !tun {
            c.arg("--user");
        }
        c.args(["-u", "vproxy", "-f"]).status()?
    };
    if !status.success() {
        bail!("log viewer exited with {status}");
    }
    Ok(())
}

/// Absolute form of a path given on the command line.
pub fn absolute(path: &Path) -> Result<PathBuf> {
    if path.is_absolute() {
        Ok(path.to_path_buf())
    } else {
        Ok(std::env::current_dir()?.join(path))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn systemd_quoting_escapes_specifiers_and_variables() {
        assert_eq!(
            shell_quote("/usr/local/bin/vproxy"),
            "/usr/local/bin/vproxy"
        );
        assert_eq!(
            shell_quote("/home/u/100%/$HOME x"),
            "\"/home/u/100%%/$$HOME x\""
        );
    }

    fn plan(tun: bool) -> ServicePlan {
        ServicePlan {
            tun,
            binary: PathBuf::from("/usr/local/bin/vproxy"),
            args: vec![
                "-f".into(),
                "/Users/me/.config/vproxy/server.txt".into(),
                "--tun".into(),
            ],
        }
    }

    #[test]
    fn plist_lists_every_argument() {
        let p = Paths {
            unit: PathBuf::from("/Library/LaunchDaemons/com.vproxy.tun.plist"),
            log: PathBuf::from("/var/log/vproxy.log"),
            label: "com.vproxy.tun".into(),
        };
        let xml = render_plist(&plan(true), &p);
        assert!(xml.contains("<string>/usr/local/bin/vproxy</string>"));
        assert!(xml.contains("<string>--tun</string>"));
        assert!(xml.contains("<string>/Users/me/.config/vproxy/server.txt</string>"));
        assert!(xml.contains("<key>Label</key><string>com.vproxy.tun</string>"));
        assert!(xml.contains("/var/log/vproxy.log"));
    }

    #[test]
    fn unit_has_root_only_for_tun() {
        let tun = render_unit(&plan(true));
        assert!(tun.contains("User=root"));
        assert!(tun.contains("ExecStart=/usr/local/bin/vproxy -f /Users/me/.config/vproxy/server.txt --tun"));
        assert!(tun.contains("WantedBy=multi-user.target"));
        let local = render_unit(&plan(false));
        assert!(!local.contains("User=root"));
        assert!(local.contains("WantedBy=default.target"));
        assert_eq!(shell_quote("a b"), "\"a b\"");
    }
}
